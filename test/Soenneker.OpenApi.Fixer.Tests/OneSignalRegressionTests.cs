[ClassDataSource<Host>(Shared = SharedType.PerTestSession)]
public sealed class OneSignalRegressionTests(Host host) : HostedUnitTest(host)
{
    [Test]
    public async ValueTask Redundant_formats_are_removed_only_from_string_schemas()
    {
        const string source = """
            {"openapi":"3.0.3","info":{"title":"Test","version":"1"},"paths":{},"components":{"schemas":{
              "Values":{"type":"array","items":{"type":"string","format":"string"}},
              "Date":{"type":"string","format":"date-time"},
              "Custom":{"type":"string","format":"custom"},
              "Payload":{"type":"object","example":{"type":"string","format":"string"}}
            }}}
            """;
        var fixer = new OpenApiPreprocessingFixer(NullLogger<OpenApiPreprocessingFixer>.Instance);
        JsonNode schemas = JsonNode.Parse(fixer.Fix(source))!["components"]!["schemas"]!;
        await Assert.That(schemas["Values"]!["items"]!["format"]).IsNull();
        await Assert.That(schemas["Values"]!["items"]!["type"]!.GetValue<string>()).IsEqualTo("string");
        await Assert.That(schemas["Date"]!["format"]!.GetValue<string>()).IsEqualTo("date-time");
        await Assert.That(schemas["Custom"]!["format"]!.GetValue<string>()).IsEqualTo("custom");
        await Assert.That(schemas["Payload"]!["example"]!["format"]!.GetValue<string>()).IsEqualTo("string");
    }

    [Test]
    [Arguments("object", "array", false, true)]
    [Arguments("array", "object", false, true)]
    [Arguments("object", "object", false, false)]
    [Arguments("object", "array", true, false)]
    public async ValueTask Only_disjoint_non_nullable_object_array_pairs_are_rewritten(string first, string second, bool nullable, bool rewrite)
    {
        string json = """
            {"components":{"schemas":{"Union":{"oneOf":[{"type":"FIRST","nullable":NULLABLE},{"type":"SECOND"}]}}}}
            """.Replace("FIRST", first).Replace("SECOND", second).Replace("NULLABLE", nullable.ToString().ToLowerInvariant());
        string result = (string)typeof(OpenApiFixer).GetMethod("NormalizeDisjointObjectArrayUnions", BindingFlags.Static | BindingFlags.NonPublic)!.Invoke(null, [json])!;
        JsonNode union = JsonNode.Parse(result)!["components"]!["schemas"]!["Union"]!;
        await Assert.That(union[rewrite ? "anyOf" : "oneOf"]).IsNotNull();
        await Assert.That(union[rewrite ? "oneOf" : "anyOf"]).IsNull();
    }

    [Test]
    public async ValueTask Generated_union_collection_checks_are_guarded_and_idempotent(CancellationToken cancellationToken)
    {
        const string source = """
            // <auto-generated/>
            public partial class ErrorUnion : IComposedTypeWrapper, IParsable
            {
                public static ErrorUnion CreateFromDiscriminatorValue(IParseNode parseNode)
                {
                    if(parseNode.GetCollectionOfPrimitiveValues<string>()?.AsList() is List<string> values)
                        return new ErrorUnion { Values = values };
                    return new ErrorUnion { Error = new Error() };
                }
            }
            """;
        string root = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(root);
        try
        {
            string path = Path.Combine(root, "ErrorUnion.cs");
            string handwritten = Path.Combine(root, "Handwritten.cs");
            await File.WriteAllTextAsync(path, source, cancellationToken);
            await File.WriteAllTextAsync(handwritten, source.Replace("// <auto-generated/>", ""), cancellationToken);
            IOpenApiFixer fixer = Resolve<IOpenApiFixer>(true);
            await fixer.SanitizeGeneratedEnumMembers(root, cancellationToken);
            string repaired = await File.ReadAllTextAsync(path, cancellationToken);
            await Assert.That(repaired).Contains("parseNode.GetObjectValue<global::Microsoft.Kiota.Abstractions.Serialization.UntypedNode>(global::Microsoft.Kiota.Abstractions.Serialization.UntypedNode.CreateFromDiscriminatorValue) is global::Microsoft.Kiota.Abstractions.Serialization.UntypedArray && parseNode.GetCollectionOfPrimitiveValues<string>()");
            await fixer.SanitizeGeneratedEnumMembers(root, cancellationToken);
            await Assert.That(await File.ReadAllTextAsync(path, cancellationToken)).IsEqualTo(repaired);
            await Assert.That(await File.ReadAllTextAsync(handwritten, cancellationToken)).IsEqualTo(source.Replace("// <auto-generated/>", ""));
        }
        finally
        {
            Directory.Delete(root, true);
        }
    }

    [Test]
    public async ValueTask OneSignal_preserves_wire_shapes(CancellationToken cancellationToken)
    {
        string output = Path.GetTempFileName();
        try
        {
            await Resolve<IOpenApiFixer>(true).Fix(Path.Combine(AppContext.BaseDirectory, "Fixtures", "onesignal.json"), output, cancellationToken);
            JsonNode document = JsonNode.Parse(await File.ReadAllTextAsync(output, cancellationToken))!;
            JsonNode schemas = document["components"]!["schemas"]!;
            foreach (string name in new[] { "NotificationTarget", "BasicNotification", "Notification", "NotificationWithMeta" })
            {
                JsonNode schema = schemas[name]!;
                await Assert.That(schema["anyOf"]).IsNull();
                await Assert.That(schema["discriminator"]).IsNull();
                await Assert.That(schema["properties"]?["included_segments"]).IsNotNull();
                await Assert.That(schema["properties"]?["include_aliases"]).IsNotNull();
            }
            await Assert.That(schemas["FilterExpressions"]!["anyOf"]!.AsArray().Count).IsEqualTo(2);
            await Assert.That(schemas["FilterExpressions"]!["discriminator"]).IsNull();
            JsonNode errors = schemas["Notification200Errors"]!;
            await Assert.That(errors["oneOf"]).IsNull();
            await Assert.That(errors["anyOf"]!.AsArray().Count).IsEqualTo(2);
            await Assert.That(errors["discriminator"]).IsNull();
            await Assert.That(schemas["NoSubscribersError"]!["items"]!["format"]).IsNull();
        }
        finally
        {
            File.Delete(output);
        }
    }
}
