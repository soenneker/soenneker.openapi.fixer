using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;

namespace Soenneker.OpenApi.Fixer;

public sealed partial class OpenApiFixer
{
    private static async ValueTask RecoverGeneratedModelMembers(string root, JsonObject? schemas, CancellationToken cancellationToken)
    {
        if (schemas == null) return;
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        var classes = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (string path in Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories))
        {
            string source = await File.ReadAllTextAsync(path, cancellationToken);
            if (!source.Contains("GeneratedCode(\"Kiota\"", StringComparison.Ordinal) && !source.Contains("<auto-generated/>", StringComparison.Ordinal)) continue;
            files[path] = source;
            CollectGeneratedClasses(source, classes);
        }
        var enums = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach ((string path, string source) in files)
        {
            cancellationToken.ThrowIfCancellationRequested();
            string repaired = RepairGeneratedMissingProperties(source, schemas, classes, enums);
            if (repaired != source) await File.WriteAllTextAsync(path, repaired, cancellationToken);
        }
        foreach ((string fullName, string source) in enums)
        {
            int separator = fullName.LastIndexOf('.');
            string? model = files.Keys.FirstOrDefault(path => Regex.IsMatch(files[path], @"(?m)^namespace\s+" + Regex.Escape(fullName[..separator]) + @"\s*(?:\r?\n|\{|;)"));
            if (model == null) continue;
            string path = Path.Combine(Path.GetDirectoryName(model)!, fullName[(separator + 1)..] + ".cs");
            if (!File.Exists(path)) await File.WriteAllTextAsync(path, source, cancellationToken);
        }
    }
}
