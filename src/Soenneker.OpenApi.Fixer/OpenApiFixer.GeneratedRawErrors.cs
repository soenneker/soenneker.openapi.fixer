using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

namespace Soenneker.OpenApi.Fixer;

public sealed partial class OpenApiFixer
{
    private static string RepairGeneratedRawError(string source, JsonObject? schemas)
    {
        const string marker = "// Preserve raw non-object error payloads.";
        if (schemas == null || source.Contains(marker)) return source;
        Match type = Regex.Match(source, @"public partial class (?<name>\w+)");
        Match ns = Regex.Match(source, @"namespace (?<name>[\w.]+)");
        string name = type.Groups["name"].Value;
        if (!type.Success || !ns.Success || schemas[name]?["x-client-raw-error-schema"] == null) return source;
        return $$"""
            // <auto-generated/>
            #nullable enable
            namespace {{ns.Groups["name"].Value}};
            {{marker}}
            public partial class {{name}} : global::Soenneker.OpenApi.Generated.OpenApiRawError
            {
                public new static {{name}} CreateFromDiscriminatorValue(global::Microsoft.Kiota.Abstractions.Serialization.IParseNode parseNode)
                {
                    global::System.ArgumentNullException.ThrowIfNull(parseNode);
                    return new {{name}} { Payload = parseNode.GetObjectValue<global::Microsoft.Kiota.Abstractions.Serialization.UntypedNode>(global::Microsoft.Kiota.Abstractions.Serialization.UntypedNode.CreateFromDiscriminatorValue) };
                }
            }
            """;
    }
}
