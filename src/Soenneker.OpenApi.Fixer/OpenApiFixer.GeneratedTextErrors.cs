using System;
using System.IO;
using System.Linq;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using System.Threading;
using System.Threading.Tasks;

namespace Soenneker.OpenApi.Fixer;

public sealed partial class OpenApiFixer
{
    private static async ValueTask RepairGeneratedTextErrors(string root, JsonObject? schemas, CancellationToken ct)
    {
        if (schemas == null || !schemas.Any(p => p.Value is JsonObject schema &&
                schema["x-client-raw-error-media-type"]?.ToString().Equals("text/plain", StringComparison.OrdinalIgnoreCase) == true)) return;
        bool used = false;
        foreach (string path in Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories))
        {
            string source = await File.ReadAllTextAsync(path, ct);
            if (!source.Contains("GeneratedCode(\"Kiota\"", StringComparison.Ordinal)) continue;
            string result = Regex.Replace(source,
                @"ApiClientBuilder\.RegisterDefaultDeserializer<(?:global::)?(?:Microsoft\.Kiota\.Serialization\.Text\.)?TextParseNodeFactory>\(\);",
                "global::Soenneker.OpenApi.Generated.OpenApiTextParseNodeFactory.Register();");
            used |= result.Contains("global::Soenneker.OpenApi.Generated.OpenApiTextParseNodeFactory.Register();", StringComparison.Ordinal);
            if (result != source) await File.WriteAllTextAsync(path, result, ct);
        }
        if (!used) return;
        await File.WriteAllTextAsync(Path.Combine(root, "OpenApiTextParseNode.cs"), """
            // <auto-generated/>
            #nullable enable
            using Microsoft.Kiota.Abstractions.Serialization;
            namespace Soenneker.OpenApi.Generated;
            internal sealed class OpenApiTextParseNode : global::Microsoft.Kiota.Serialization.Text.TextParseNode, IParseNode
            {
                private readonly string _text;
                internal OpenApiTextParseNode(string text) : base(text) => _text = text;
                T IParseNode.GetObjectValue<T>(ParsableFactory<T> factory)
                {
                    if (typeof(T) == typeof(UntypedNode)) return (T)(object)new UntypedString(_text);
                    T value = factory(this);
                    if (value is OpenApiRawError) return value;
                    throw new global::System.InvalidOperationException("Text responses cannot deserialize structured models.");
                }
            }
            """, ct);
        await File.WriteAllTextAsync(Path.Combine(root, "OpenApiTextParseNodeFactory.cs"), """
            // <auto-generated/>
            #nullable enable
            using System;
            using System.IO;
            using System.Threading;
            using System.Threading.Tasks;
            using Microsoft.Kiota.Abstractions.Serialization;
            namespace Soenneker.OpenApi.Generated;
            internal sealed class OpenApiTextParseNodeFactory : IParseNodeFactory
            {
                public string ValidContentType => "text/plain";
                internal static void Register()
                {
                    var factories = ParseNodeFactoryRegistry.DefaultInstance.ContentTypeAssociatedFactories;
                    if (!factories.TryGetValue("text/plain", out var existing) || existing.GetType() == typeof(global::Microsoft.Kiota.Serialization.Text.TextParseNodeFactory))
                        factories["text/plain"] = new OpenApiTextParseNodeFactory();
                }
                public IParseNode GetRootParseNode(string contentType, Stream content)
                {
                    Validate(contentType, content);
                    using var reader = new StreamReader(content);
                    return new OpenApiTextParseNode(reader.ReadToEnd());
                }
                public async Task<IParseNode> GetRootParseNodeAsync(string contentType, Stream content, CancellationToken cancellationToken = default)
                {
                    Validate(contentType, content);
                    cancellationToken.ThrowIfCancellationRequested();
                    using var reader = new StreamReader(content);
                    string text = await reader.ReadToEndAsync().ConfigureAwait(false);
                    cancellationToken.ThrowIfCancellationRequested();
                    return new OpenApiTextParseNode(text);
                }
                private void Validate(string contentType, Stream content)
                {
                    if (!ValidContentType.Equals(contentType, StringComparison.OrdinalIgnoreCase)) throw new ArgumentOutOfRangeException(nameof(contentType));
                    if (content == null) throw new ArgumentNullException(nameof(content));
                }
            }
            """, ct);
    }
}
